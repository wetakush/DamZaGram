import { save, entries, open } from '../../../../plugins/builtin/bookmarks/main.js';
const { eq, assert } = sandbox;
const message = mock.message({ selfId: mock.self.id, text: 'needle' });
save(message);
save(message);
eq(entries().length, 1, 'deduplicated');
save(mock.message({ selfId: 'other' }));
eq(entries().length, 1, 'foreign account ignored');
open();
mock.submit(mock.lastPanel(), 'needle');
assert(mock.panelText().includes('needle'));
mock.click(mock.lastPanel(), 'Открыть сообщение');
eq(mock.opened[0].messageId, message.id);
mock.self.id = 'other';
eq(entries().length, 0, 'isolated storage');
mock.click(mock.lastPanel(), 'Открыть сообщение');
eq(mock.opened.length, 1, 'stale account panel guarded');
mock.self.id = '1';
mock.click(mock.lastPanel(), 'Удалить закладку');
eq(entries().length, 0);
